    ('Отделение подготовки (специалистов)', 'отделения подготовки (специалистов)'),
    ('Метеорологическая станция', 'метеорологической станции'),
    ('1 рота ПРТД БпС', '1 роты ПРТД БпС'),
    ('1 взвод ТЯЖ БПЛА КТ', '1 взвода ТЯЖ БПЛА КТ'),
    ('1 рота НРТК', '1 роты НРТК'),
    ('2 рота БпЛА Р-У', '2 роты БпЛА Р-У'),
    ('РОТА FPV КТ', 'роты FPV КТ'),
    ('Взвод БпЛА КТ-У', 'взвода БпЛА КТ-У'),
    ('Т-Э рота', 'Т-Э роты'),
    ('ВЗВОД ТЕХ.ОБЕСПЕЧЕНИЯ', 'взвода тех.обеспечения'),
